#!/usr/bin/env node
/* Heavy Pockets storefront preview v3: static page generator.
   Run: node theme/v3/build.js
   Reads src/products.json, src/pricing.json, and src/printify-snapshot.json,
   checks the approved colors against the Printify snapshot, then writes
   assets/catalog.js and every page. No dependencies. */
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const ROOT = path.resolve(DIR, '../..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(DIR, p), 'utf8'));
const SRC = read('src/products.json');
const PRICING = read('src/pricing.json');
const SNAP = read('src/printify-snapshot.json');
const SIZE_ORDER = ['S', 'M', 'L', 'XL', '2XL', '3XL', '4XL', '5XL'];
const LARGE = new Set(['2XL', '3XL', '4XL', '5XL']);
const SNAP_DATE = 'Nov 7, 2026';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const money = (c) => '$' + (c / 100).toFixed(2);
const moneyShort = (c) => (c % 100 ? money(c) : '$' + c / 100);

/* ---------- catalog: hand-written records + Printify snapshot ---------- */
const errors = [];
const products = SRC.products.map((p) => {
  const snap = SNAP.products[p.slug];
  if (!snap) throw new Error('missing snapshot for ' + p.slug);
  if (snap.printify_id !== p.printify_id) errors.push(`${p.slug}: Printify id mismatch`);
  const enabled = [...new Set(snap.variants.map((v) => v.color))].sort();
  if (JSON.stringify(enabled) !== JSON.stringify([...p.colors].sort())) {
    errors.push(`${p.slug}: approved colors ${p.colors} != Printify enabled ${enabled}`);
  }
  const tier = PRICING.tiers[p.tier];
  const blank = SRC.blanks[p.blank];
  const sizesOffered = SIZE_ORDER.filter((s) => snap.variants.some((v) => v.size === s));
  const colors = p.colors.map((name) => {
    const vs = snap.variants.filter((v) => v.color === name);
    return {
      name,
      slug: slugify(name),
      hex: snap.swatches[name],
      images: snap.images[name],
      sizes: SIZE_ORDER.filter((s) => vs.some((v) => v.size === s)).map((s) => {
        const v = vs.find((x) => x.size === s);
        return { size: s, ok: v.printify_available, id: v.id };
      }),
    };
  });
  colors.forEach((c) => {
    if (!c.images || !c.images[p.card_view]) errors.push(`${p.slug}/${c.name}: no ${p.card_view} image`);
    if (!/^#[0-9A-F]{6}$/.test(c.hex || '')) errors.push(`${p.slug}/${c.name}: bad swatch`);
  });
  const isHoodie = p.blank === 'g18500';
  return {
    slug: p.slug, name: p.name, kind: p.kind, printifyId: p.printify_id,
    priceCents: tier.base_cents, tierLabel: tier.label,
    cardView: p.card_view, colors, sizesOffered,
    views: isHoodie ? ['front', 'back', 'back-hood', 'folded'] : ['front', 'back', 'flatlay', 'folded'],
    blurb: p.blurb, story: p.story, decoration: p.decoration, provider: p.provider,
    blank, care: isHoodie ? blank[p.care] : blank.care, art: p.art, isHoodie,
  };
});
// Indigo Blue embroidery was removed on purpose. Fail loudly if it ever returns.
products.forEach((p) => p.colors.forEach((c) => { if (/indigo/i.test(c.name)) errors.push(`${p.slug}: Indigo Blue must not be offered`); }));
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const catalog = {
  snapshotDate: SNAP_DATE,
  sizeOrder: SIZE_ORDER,
  largeSizes: [...LARGE],
  pricingStatus: 'approved',
  sizeAdjustCents: PRICING.larger_size_adjustment.cents_by_size,
  shippingNote: PRICING.shipping_note,
  products: products.map((p) => ({
    slug: p.slug, name: p.name, kind: p.kind, priceCents: p.priceCents, cardView: p.cardView,
    views: p.views,
    colors: p.colors.map((c) => ({ name: c.name, slug: c.slug, hex: c.hex, images: c.images, sizes: c.sizes.map((s) => ({ size: s.size, ok: s.ok })) })),
  })),
};
fs.mkdirSync(path.join(DIR, 'assets'), { recursive: true });
fs.writeFileSync(path.join(DIR, 'assets/catalog.js'),
  '/* Generated by build.js from src/*.json. Do not edit by hand. Prices are PROVISIONAL. */\n' +
  'window.HP_CATALOG = ' + JSON.stringify(catalog) + ';\n');
fs.copyFileSync(path.join(ROOT, 'brand/v2/brand-tokens.css'), path.join(DIR, 'assets/brand-tokens.css'));
fs.copyFileSync(path.join(ROOT, 'brand/v3/wordmark/heavy-pockets-wordmark.svg'), path.join(DIR, 'assets/wordmark.svg'));
for (const s of ['agate-hero', 'jasper', 'petoskey', 'leland']) {
  fs.mkdirSync(path.join(DIR, 'img/stones'), { recursive: true });
  for (const st of ['dry', 'wet']) {
    fs.copyFileSync(path.join(ROOT, `theme/v2/img/${s}-${st}.webp`), path.join(DIR, `img/stones/${s}-${st}.webp`));
  }
}

