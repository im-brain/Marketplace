#!/usr/bin/env node
/* Heavy Pockets coming-soon page: Worker generator.
   Run: node site/coming-soon/build.js
   Reads src/ and writes:
     dist/index.js   the Worker (routing, security headers, /api/dibs), copied from src/worker.js
     dist/site.js    the page HTML (PAGE) plus every asset, base64-encoded (FILES)
     preview/index.html  one standalone file for the private claude.ai preview
                         (assets inlined, signup switched off, copy options switcher)
   No dependencies. The images in src/assets/logo/ are made by make_images.js (Playwright). */
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const SRC = path.join(DIR, 'src');
const ROOT = path.resolve(DIR, '../..');
const read = (p) => fs.readFileSync(path.join(SRC, p), 'utf8');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const TYPES = { '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp' };
// Every file the page or the Worker serves, by public path.
const ASSETS = [
  '/assets/logo/favicon.svg',
  '/assets/logo/favicon-32.png',
  '/assets/logo/apple-touch-icon.png',
  '/assets/logo/og-v3.jpg',
  '/assets/hero/shore-wide.webp',
  '/assets/hero/shore-tall.webp',
  '/assets/mascot/rockhound.svg',
];

/* ---------- inputs ---------- */
const copy = JSON.parse(read('copy.json'));
const bubble = copy.bubble[copy.chosen];
if (!bubble) throw new Error('copy.json: chosen option "' + copy.chosen + '" is missing');

// The approved v3 wordmark, single color (currentColor): cream at night, deep teal by day.
const wm = fs.readFileSync(path.join(ROOT, 'brand/v3/wordmark/heavy-pockets-wordmark.svg'), 'utf8');
const wmPaths = wm.match(/<path\b[^>]*\/>/g);
if (!wmPaths || !/viewBox="0 0 1243 204"/.test(wm)) throw new Error('wordmark SVG changed shape; update the viewBox in page.html');

const files = {};
for (const p of ASSETS) {
  const f = path.join(SRC, p.replace(/^\/assets\//, 'assets/'));
  if (!fs.existsSync(f)) throw new Error('missing asset ' + f + (p.includes('/logo/') && !p.endsWith('.svg') ? ' (run: node site/coming-soon/make_images.js)' : ''));
  files[p] = { type: TYPES[path.extname(p)], bytes: fs.readFileSync(f) };
}

let page = read('page.html')
  .replace('<!--WORDMARK-->', wmPaths.join(''))
  .replace('<!--BUBBLE_LINE-->', esc(bubble.line))
  .replace('<!--BUBBLE_PUNCH-->', esc(bubble.punch));

/* ---------- checks: Brian's rules and the honesty rules ---------- */
const problems = [];
const shopperText = page + read('worker.js') + JSON.stringify(copy.bubble);
if (/—/.test(shopperText)) problems.push('em dash found');
if (/supplier|printify/i.test(shopperText)) problems.push('"supplier" or "Printify" in shopper text');
if (/\bsocks?\b/i.test(page)) problems.push('page still mentions socks');
if (/\bcart\b|checkout|add to bag|\$\d/i.test(page)) problems.push('page mentions a cart, checkout, or a price');
if (/Heavy Pockets Co\.<\/|wordmark\.svg/.test(page)) problems.push('old wordmark reference');
for (const m of page.matchAll(/(?:src|href|srcset)="(\/assets\/[^"]+)"/g)) if (!files[m[1]]) problems.push('page links a missing asset ' + m[1]);
if (!/env\.DIBS/.test(read('worker.js'))) problems.push('worker no longer uses the DIBS binding');
if (problems.length) { console.error('build stopped:\n  ' + problems.join('\n  ')); process.exit(1); }

/* ---------- Worker modules ---------- */
const livePage = page.replace('<!--PREVIEW_BAR-->\n', '');
fs.mkdirSync(path.join(DIR, 'dist'), { recursive: true });
fs.copyFileSync(path.join(SRC, 'worker.js'), path.join(DIR, 'dist/index.js'));
let site = '// Generated by site/coming-soon/build.js. Do not edit by hand.\n' +
  'const b64 = s => Uint8Array.from(atob(s), c => c.charCodeAt(0));\n' +
  'export const PAGE = ' + JSON.stringify(livePage) + ';\n' +
  'export const FILES = {\n';
for (const [p, f] of Object.entries(files)) site += '  ' + JSON.stringify(p) + ': { type: ' + JSON.stringify(f.type) + ', bytes: b64(' + JSON.stringify(f.bytes.toString('base64')) + ') },\n';
site += '};\n';
fs.writeFileSync(path.join(DIR, 'dist/site.js'), site);

/* ---------- private preview: one file, assets inlined, signup off ---------- */
const dataUri = (p) => 'data:' + files[p].type + ';base64,' + files[p].bytes.toString('base64');
let preview = page.replace(/(["(])(\/assets\/[^")\s]+)/g, (all, q, p) => (files[p] ? q + dataUri(p) : all));
preview = preview.replace('<title>Heavy Pockets Co. | Coming soon</title>', '<title>Coming Soon Preview</title>\n<meta name="robots" content="noindex, nofollow">');
// The speech bubble switcher was removed after Brian picked option A (Nov 7, 2026).
const bar = `<div class="pv" role="region" aria-label="Preview notes">
<p><b>Private preview.</b> The signup can't save anything here. It only works on heavypocketsco.com.</p>
</div>
<style>.pv{background:#E8B954;color:#101D2C;padding:8px 16px;font:400 15px/1.4 "Atkinson Hyperlegible Next",system-ui,sans-serif;text-align:center;border-bottom:3px solid #101D2C}
.pv p{margin:0}</style>`;
const pvScript = `<script>
(() => {
  // Preview only: keep the form from trying to send.
  window.addEventListener('submit', e => {
    e.preventDefault(); e.stopPropagation();
    const s = document.querySelector('.status-line');
    s.removeAttribute('data-state');
    s.textContent = "Preview only: nothing was saved. On the live page, this saves your email to the list.";
  }, true);
})();
</script>`;
preview = preview.replace('<!--PREVIEW_BAR-->', bar).replace('</body>', pvScript + '\n</body>');
fs.mkdirSync(path.join(DIR, 'preview'), { recursive: true });
fs.writeFileSync(path.join(DIR, 'preview/index.html'), preview);

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log('copy option:', copy.chosen, '|', bubble.line, bubble.punch);
console.log('dist/index.js', kb(fs.statSync(path.join(DIR, 'dist/index.js')).size));
console.log('dist/site.js ', kb(site.length), '(' + Object.keys(files).length + ' assets)');
console.log('preview/index.html', kb(preview.length));
