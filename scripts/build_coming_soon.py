"""Build the coming-soon Worker from site/prototype/coming-soon.html.

Run from the repo root:  python3 scripts/build_coming_soon.py

What it does, in plain terms:
  1. Reads the coming-soon page and pulls its local CSS and JS files into it.
  2. Finds every image the page uses (assets/... in src, href, and CSS url())
     and points it at /assets/..., so the Worker can serve each image as a file
     that browsers keep (smaller page, faster repeat visits).
  3. Writes worker/dist/site.js (the page plus the images) and copies
     worker/src/index.js next to it. Those two files are what Cloudflare runs.

worker/dist/ is rebuilt every time and is not saved in git.
"""
import base64
import json
import mimetypes
import pathlib
import re
import shutil

REPO = pathlib.Path(__file__).resolve().parent.parent
PROTO = REPO / "site" / "prototype"
SRC = PROTO / "coming-soon.html"
DIST = REPO / "worker" / "dist"
TYPES = {".svg": "image/svg+xml", ".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg"}


def local(path):
    return not re.match(r"^(https?:)?//", path)


def build():
    html = SRC.read_text()
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">',
                  lambda m: "<style>\n" + (PROTO / m.group(1)).read_text() + "</style>" if local(m.group(1)) else m.group(0), html)
    html = re.sub(r'<script src="([^"]+)"></script>',
                  lambda m: "<script>\n" + (PROTO / m.group(1)).read_text() + "</script>" if local(m.group(1)) else m.group(0), html)
    files = {}

    def asset(m):
        path = m.group(2)
        f = PROTO / path
        if not f.is_file():
            raise SystemExit(f"missing asset: {path}")
        files["/" + path] = f
        return m.group(1) + "/" + path + m.group(3)

    html = re.sub(r'((?:src|href)=")(assets/[^"]+)(")', asset, html)
    html = re.sub(r'(url\()(assets/[^)]+)(\))', asset, html)
    # The share image is linked with its full web address, so add it by hand.
    files["/assets/logo/og-retro.jpg"] = PROTO / "assets" / "logo" / "og-retro.jpg"
    if re.search(r'(?:src|href)="(?!/|https?:|mailto:|#|data:)', html):
        raise SystemExit("a local link was not rewritten; check coming-soon.html")

    DIST.mkdir(parents=True, exist_ok=True)
    out = ["// Generated by scripts/build_coming_soon.py. Do not edit by hand.",
           "const b64 = s => Uint8Array.from(atob(s), c => c.charCodeAt(0));",
           "export const PAGE = " + json.dumps(html) + ";",
           "export const FILES = {"]
    total = len(html)
    for web, f in sorted(files.items()):
        kind = TYPES.get(f.suffix) or mimetypes.guess_type(f.name)[0] or "application/octet-stream"
        data = f.read_bytes()
        total += len(data)
        out.append(f"  {json.dumps(web)}: {{ type: {json.dumps(kind)}, bytes: b64({json.dumps(base64.b64encode(data).decode())}) }},")
    out.append("};")
    (DIST / "site.js").write_text("\n".join(out) + "\n")
    shutil.copy(REPO / "worker" / "src" / "index.js", DIST / "index.js")
    size = (DIST / "site.js").stat().st_size
    print(f"built worker/dist: page {len(html) // 1024} KB, {len(files)} files, site.js {size // 1024} KB")
    if size > 2_800_000:
        raise SystemExit("site.js is close to Cloudflare's free 3 MB limit; shrink an image")
    return DIST


if __name__ == "__main__":
    build()
